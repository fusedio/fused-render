export const TASK_ICON_COUNT = TASK_ICON_NAMES.length;

/** The sprite URL and symbol id for a slot; null when the slot is unknown. */
export function taskIconName(slot: number | null | undefined): string | null {
  if (slot === null || slot === undefined || !Number.isInteger(slot)) return null;
  if (slot < 0 || slot >= TASK_ICON_COUNT) return null;
  return TASK_ICON_NAMES[slot];
}

// The sprite sits in frontend/public, so Vite copies it next to the shell
// bundle: under `base` (/static/shell-dist/ packaged, the dev server's root
// in dev) — the same resolution the favicon uses (platform/lib/hooks.ts).
export const TASK_ICON_SPRITE = `${import.meta.env.BASE_URL}task-icons.svg`;

/** `<use href>` target for a slot, or null. */
export function taskIconHref(slot: number | null | undefined): string | null {
  const name = taskIconName(slot);
  return name ? `${TASK_ICON_SPRITE}#ti-${name}` : null;
}
